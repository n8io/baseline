// pnpm sdk-generate: writes clients/sdk/openapi.json from the app's own OpenAPI document (the build
// booted on memory adapters, as api-check does), with clients/environments.json as its `servers`
// (one per environment, `description` its name), and generates clients/sdk/sdk.ts from it: one typed
// function per operation, named by its operationId. Run it after any change to a route; CI fails
// when the committed files differ from what it writes. This is the only file that imports the generator.
import { readFileSync, writeFileSync } from "node:fs";
import { generate } from "orval";
import { documentSave } from "./api-check.ts";
import { argsParse } from "./args.ts";
import { processRun } from "./process-run.ts";

const sdk = "clients/sdk";

export const sdkGenerate = async (): Promise<void> => {
	const environments = JSON.parse(
		readFileSync("clients/environments.json", "utf8"),
	) as Record<string, string>;
	await documentSave({
		directory: ".",
		file: `${sdk}/openapi.json`,
		port: 3102,
		prepare: (document) => ({
			...(document as object),
			servers: Object.entries(environments).map(([description, url]) => ({
				description,
				url,
			})),
		}),
	});
	await generate({
		input: { target: `${sdk}/openapi.json` },
		output: {
			client: "fetch",
			mode: "single",
			override: {
				// No version or date, so the same document always writes the same file.
				header: () => [
					"Generated by `pnpm sdk-generate` from openapi.json. Do not edit.",
				],
				// Types only: every value sdk.ts exports is an operation's function.
				enumGenerationType: "union",
				mutator: { name: "sdkFetch", path: `${sdk}/sdk-fetch.ts` },
			},
			target: `${sdk}/sdk.ts`,
			// Imports carry the .ts extension, as everywhere in this app.
			tsconfig: { compilerOptions: { allowImportingTsExtensions: true } },
		},
	});
	// orval also exports each operation's URL builder (getFooCreateUrl); keep them module-private,
	// so the SDK's value exports are exactly its operations.
	const target = `${sdk}/sdk.ts`;
	writeFileSync(
		target,
		readFileSync(target, "utf8").replaceAll(
			/^export const (get\w+Url) =/gm,
			"const $1 =",
		),
	);
	processRun({
		command: "pnpm",
		args: ["exec", "biome", "check", "--write", sdk],
		options: { inherit: true },
	});
};

const usage = `Usage: pnpm sdk-generate

Writes clients/sdk/openapi.json and clients/sdk/sdk.ts from the app's OpenAPI document.

  -h, --help  this help`;

if (import.meta.main && argsParse({ options: {}, usage }) !== undefined) {
	sdkGenerate().catch((error: unknown) => {
		console.error(error instanceof Error ? error.message : error);
		process.exitCode = 1;
	});
}
