// pnpm sdk-generate: writes clients/sdk/openapi.json from the app's own OpenAPI document (the build
// booted on memory adapters, as api-check does) and generates clients/sdk/sdk.ts from it: one typed
// function per operation, named by its operationId. Run it after any change to a route; CI fails
// when the committed files differ from what it writes. The generator is named only in this file.
import { spawnSync } from "node:child_process";
import { generate } from "orval";
import { documentSave } from "./api-check.ts";

const sdk = "clients/sdk";

export const sdkGenerate = async (): Promise<void> => {
	await documentSave({
		directory: ".",
		file: `${sdk}/openapi.json`,
		port: 3102,
	});
	await generate({
		input: { target: `${sdk}/openapi.json` },
		output: {
			client: "fetch",
			mode: "single",
			override: {
				// No version or date, so the same document always writes the same file.
				header: () => [
					"Generated by `pnpm sdk-generate` from openapi.json. Do not edit.",
				],
				// Types only: every value sdk.ts exports is an operation's function.
				enumGenerationType: "union",
				mutator: { name: "sdkFetch", path: `${sdk}/sdk-fetch.ts` },
			},
			target: `${sdk}/sdk.ts`,
			// Imports carry the .ts extension, as everywhere in this app.
			tsconfig: { compilerOptions: { allowImportingTsExtensions: true } },
		},
	});
	const format = spawnSync("pnpm", ["exec", "biome", "check", "--write", sdk], {
		stdio: "inherit",
	});
	if (format.status !== 0) throw new Error(`biome check ${sdk} failed`);
};

if (import.meta.main) {
	sdkGenerate().catch((error: unknown) => {
		console.error(error instanceof Error ? error.message : error);
		process.exit(1);
	});
}
